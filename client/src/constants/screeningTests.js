export const SCREENING_TESTS = [PHQ9, GAD7];

export function scoreTest(test, answers) {
  const values = test.items.map((_, i) => answers[i] ?? 0);
  const total = values.reduce((a, b) => a + b, 0);
  const band = test.bands.find((b) => total <= b.max) ?? test.bands[test.bands.length - 1];
  const selfHarmFlag =
    test.selfHarmItemIndex != null && (answers[test.selfHarmItemIndex] ?? 0) > 0;
  return { total, band, selfHarmFlag };
}
