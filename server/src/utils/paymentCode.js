// Короткий код сесії, який клієнт вказує в коментарі до банківського
// переказу — щоб однозначно розрізняти перекази різних клієнтів з
// однаковою (або близькою) сумою, коли банка приватна й перевірка йде
// не через AI, а напряму через реальну виписку Monobank (fetchJarStatement).
//
// Детерміновано обчислюється з sessionId — без нового поля в БД і без
// запиту на сервер. Той самий алгоритм продубльовано на фронтенді
// (client/src/utils/paymentCode.js), щоб код, показаний клієнту, завжди
// збігався з тим, що шукає бекенд.
function getPaymentCode(sessionId) {
  return sessionId.slice(-6).toUpperCase();
}

module.exports = { getPaymentCode };
